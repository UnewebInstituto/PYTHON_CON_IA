a1 = np.array([[1, 1],
               [2, 2]])

a2 = np.array([[3, 3],
               [4, 4]])
a1
array([[1, 1],
       [2, 2]])
a2
array([[3, 3],
       [4, 4]])
np.vstack((a1,a2))
array([[1, 1],
       [2, 2],
       [3, 3],
       [4, 4]])
np.hstack((a1,a2))
array([[1, 1, 3, 3],
       [2, 2, 4, 4]])
